type tiffInfo struct {
	little, big                                    bool
	first                                          uint64
	countBytes, offsetBytes, entrySize, headerSize int
}

func tiffLayout(data []byte) (tiffInfo, bool) {
	if len(data) < 4 {
		return tiffInfo{}, false
	}
	little := bytes.Equal(data[:2], []byte("II"))
	bigEndian := bytes.Equal(data[:2], []byte("MM"))
	if !little && !bigEndian {
		return tiffInfo{}, false
	}
	var order binary.ByteOrder
	if bigEndian {
		order = binary.BigEndian
	} else {
		order = binary.LittleEndian
	}
	version := order.Uint16(data[2:4])
	if version == 42 {
		info := tiffInfo{little: little, countBytes: 2, offsetBytes: 4, entrySize: 12, headerSize: 8}
		if len(data) >= info.headerSize {
			info.first = uint64(order.Uint32(data[4:8]))
		}
		return info, true
	}
	if version == 43 {
		info := tiffInfo{little: little, big: true, countBytes: 8, offsetBytes: 8, entrySize: 20, headerSize: 16}
		if len(data) >= info.headerSize {
			info.first = order.Uint64(data[8:16])
		}
		return info, true
	}
	return tiffInfo{}, false
}

func tiffOrder(info tiffInfo) binary.ByteOrder {
	if info.little {
		return binary.LittleEndian
	}
	return binary.BigEndian
}
func tiffTypeSize(t uint16) uint64 {
	switch t {
	case 1, 2, 6, 7:
		return 1
	case 3, 8:
		return 2
	case 4, 9:
		return 4
	case 5, 10, 12:
		return 8
	case 11:
		return 4
	default:
		return 1
	}
}

type tiffEntry struct {
	tag         uint16
	typ         uint16
	count       uint64
	value       []byte
	valueOffset uint64
	inline      bool
	entryOffset int
}

func tiffEntryPointer(info tiffInfo, entry tiffEntry) (uint64, bool) {
	ord := tiffOrder(info)
	if info.big {
		if len(entry.value) < 8 {
			return 0, false
		}
		return ord.Uint64(entry.value[:8]), true
	}
	if len(entry.value) < 4 {
		return 0, false
	}
	return uint64(ord.Uint32(entry.value[:4])), true
}

