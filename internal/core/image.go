func containsAny(data []byte, markers [][]byte) []string {
	lower := bytes.ToLower(data)
	hits := make([]string, 0)
	for _, marker := range markers {
		name := string(marker)
		if bytes.Contains(lower, bytes.ToLower(marker)) {
			hits = append(hits, name)
		}
	}
	return hits
}

// blobMarkerHits mirrors the upstream container-level evidence shape. Image
// inspectors expose flat marker names, while document/SVG blob scans label
// provenance markers and AI hints separately so callers can distinguish the
// two kinds of evidence.
func blobMarkerHits(data []byte) (bool, bool, []string) {
	lower := bytes.ToLower(data)
	hits := make([]string, 0)
	hasC2PA, hasAI := false, false
	for _, marker := range c2paMarkers {
		if bytes.Contains(lower, bytes.ToLower(marker)) {
			hasC2PA = true
			hits = append(hits, "marker:"+string(marker))
		}
	}
	for _, hint := range aiMetaHints {
		if !bytes.Contains(lower, bytes.ToLower(hint)) {
			continue
		}
		hasAI = true
		label := string(hint)
		duplicate := false
		for _, finding := range hits {
			if strings.TrimPrefix(finding, "marker:") == label || strings.TrimPrefix(finding, "ai:") == label {
				duplicate = true
				break
			}
		}
		if !duplicate {
			hits = append(hits, "ai:"+label)
		}
	}
	if len(hits) > 30 {
		hits = hits[:30]
	}
	return hasC2PA, hasAI || hasC2PA, hits
}

func isC2PAHit(hits []string) bool {
	for _, hit := range hits {
		low := strings.ToLower(hit)
		if low == "c2pa" || low == "jumb" || low == "contentcredentials" || low == "contentauth" {
			return true
		}
	}
	return false
}

