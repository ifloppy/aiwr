func tiffIFDBlockEnd(data []byte, info tiffInfo, offset uint64) uint64 {
	if offset >= uint64(len(data)) || offset+uint64(info.countBytes) > uint64(len(data)) {
		return offset
	}
	ord := tiffOrder(info)
	var count uint64
	if info.big {
		count = ord.Uint64(data[offset : offset+8])
	} else {
		count = uint64(ord.Uint16(data[offset : offset+2]))
	}
	base := offset + uint64(info.countBytes)
	if count > (^uint64(0)-base)/uint64(info.entrySize) {
		return uint64(len(data))
	}
	end := base + count*uint64(info.entrySize)
	if end > ^uint64(0)-uint64(info.offsetBytes) {
		return uint64(len(data))
	}
	end += uint64(info.offsetBytes)
	if end > uint64(len(data)) {
		return uint64(len(data))
	}
	return end
}

func tiffSubIFDHasMarkers(data []byte, info tiffInfo, offset uint64) bool {
	if offset == 0 {
		return false
	}
	entries, _, valid := readTIFFIFD(data, info, offset)
	if !valid {
		return false
	}
	end := tiffIFDBlockEnd(data, info, offset)
	if end > uint64(len(data)) {
		end = uint64(len(data))
	}
	if offset < end && len(containsAny(data[offset:end], append(aiMetaHints, c2paMarkers...))) > 0 {
		return true
	}
	for _, entry := range entries {
		if len(containsAny(tiffEntryPayload(entry), append(aiMetaHints, c2paMarkers...))) > 0 {
			return true
		}
	}
	return false
}

type tiffIFDRecord struct {
	entries  []tiffEntry
	next     uint64
	blockEnd uint64
}

// collectTIFFIFDs walks the IFD graph once and records the original byte
// extent of every reachable directory. Keeping the original extents is what
// lets stripTIFF compact dropped entries in place without moving image data
// referenced by StripOffsets/TileOffsets.
func collectTIFFIFDs(data []byte, info tiffInfo) map[uint64]tiffIFDRecord {
	ifds := map[uint64]tiffIFDRecord{}
	todo := []uint64{info.first}
	for len(todo) > 0 && len(ifds) < 4096 {
		off := todo[len(todo)-1]
		todo = todo[:len(todo)-1]
		if off == 0 || off >= uint64(len(data)) {
			continue
		}
		if _, seen := ifds[off]; seen {
			continue
		}
		entries, next, valid := readTIFFIFD(data, info, off)
		if !valid {
			continue
		}
		record := tiffIFDRecord{entries: entries, next: next, blockEnd: tiffIFDBlockEnd(data, info, off)}
		if record.blockEnd < off {
			record.blockEnd = uint64(len(data))
		}
		if record.blockEnd > uint64(len(data)) {
			record.blockEnd = uint64(len(data))
		}
		ifds[off] = record
		if next != 0 {
			todo = append(todo, next)
		}
		for _, entry := range entries {
			if isTIFFPointerTag(entry.tag) {
				if ptr, ok := tiffEntryPointer(info, entry); ok && ptr != 0 {
					todo = append(todo, ptr)
				}
			}
		}
	}
	return ifds
}

func tiffEntryByteSize(entry tiffEntry) (uint64, bool) {
	size := tiffTypeSize(entry.typ)
	if entry.count != 0 && size > ^uint64(0)/entry.count {
		return 0, false
	}
	return entry.count * size, true
}

// tiffEntryPayload returns only the declared value bytes. Inline TIFF fields
// are padded to four/eight bytes, and scanning that padding can create false
// marker hits that Python's reference parser does not report.
func tiffEntryPayload(entry tiffEntry) []byte {
	size, ok := tiffEntryByteSize(entry)
	if !ok || size == 0 || len(entry.value) == 0 {
		return nil
	}
	if size < uint64(len(entry.value)) {
		return entry.value[:int(size)]
	}
	return entry.value
}

func tiffIFDOffsets(ifds map[uint64]tiffIFDRecord) []uint64 {
	offsets := make([]uint64, 0, len(ifds))
	for off := range ifds {
		offsets = append(offsets, off)
	}
	sort.Slice(offsets, func(i, j int) bool { return offsets[i] < offsets[j] })
	return offsets
}

func appendTIFFOffset(dst []byte, info tiffInfo, value uint64) []byte {
	ord := tiffOrder(info)
	if info.big {
		var raw [8]byte
		ord.PutUint64(raw[:], value)
		return append(dst, raw[:]...)
	}
	var raw [4]byte
	ord.PutUint32(raw[:], uint32(value))
	return append(dst, raw[:]...)
}

func tiffRangeCovered(ranges [][2]uint64, start, end uint64) bool {
	for _, current := range ranges {
		if current[0] <= start && end <= current[1] {
			return true
		}
	}
	return false
}

func collectTIFFDroppedIFD(data []byte, info tiffInfo, ifds map[uint64]tiffIFDRecord, offset uint64, dropRanges, dropIFDRanges *[][2]uint64, seen map[uint64]bool) {
	if offset == 0 || seen[offset] {
		return
	}
	record, ok := ifds[offset]
	if !ok {
		return
	}
	seen[offset] = true
	*dropIFDRanges = append(*dropIFDRanges, [2]uint64{offset, record.blockEnd})
	for _, entry := range record.entries {
		if isTIFFSubIFDTag(entry.tag) {
			if ptr, pointerOK := tiffEntryPointer(info, entry); pointerOK {
				collectTIFFDroppedIFD(data, info, ifds, ptr, dropRanges, dropIFDRanges, seen)
			}
			continue
		}
		if entry.inline || entry.valueOffset == 0 || len(tiffEntryPayload(entry)) == 0 {
			continue
		}
		valueEnd := entry.valueOffset + uint64(len(tiffEntryPayload(entry)))
		if valueEnd >= entry.valueOffset && valueEnd <= uint64(len(data)) {
			*dropRanges = append(*dropRanges, [2]uint64{entry.valueOffset, valueEnd})
		}
	}
}

func zeroTIFFIFD(data []byte, info tiffInfo, offset uint64, out []byte, zeroRange func(uint64, uint64), seen map[uint64]bool) {
	if offset == 0 || seen[offset] {
		return
	}
	seen[offset] = true
	entries, next, valid := readTIFFIFD(data, info, offset)
	if !valid {
		return
	}
	end := tiffIFDBlockEnd(data, info, offset)
	zeroRange(offset, end)
	for _, entry := range entries {
		if isTIFFPointerTag(entry.tag) {
			if ptr, ok := tiffEntryPointer(info, entry); ok {
				zeroTIFFIFD(data, info, ptr, out, zeroRange, seen)
			}
		} else if !entry.inline && entry.valueOffset > 0 && len(entry.value) > 0 {
			zeroRange(entry.valueOffset, entry.valueOffset+uint64(len(entry.value)))
		}
	}
	if next != 0 {
		zeroTIFFIFD(data, info, next, out, zeroRange, seen)
	}
}

func readTIFFIFD(data []byte, info tiffInfo, offset uint64) ([]tiffEntry, uint64, bool) {
	if offset > uint64(len(data)) || offset+uint64(info.countBytes) > uint64(len(data)) {
		return nil, 0, false
	}
	ord := tiffOrder(info)
	var count uint64
	if info.big {
		count = ord.Uint64(data[offset : offset+8])
	} else {
		count = uint64(ord.Uint16(data[offset : offset+2]))
	}
	declaredCount := count
	if count > 4096 {
		count = 4096
	}
	entries := make([]tiffEntry, 0, int(count))
	base := offset + uint64(info.countBytes)
	for i := uint64(0); i < count; i++ {
		eoff := base + i*uint64(info.entrySize)
		if eoff+uint64(info.entrySize) > uint64(len(data)) {
			break
		}
		e := int(eoff)
		tag := ord.Uint16(data[e : e+2])
		typ := ord.Uint16(data[e+2 : e+4])
		var num uint64
		if info.big {
			num = ord.Uint64(data[e+4 : e+12])
		} else {
			num = uint64(ord.Uint32(data[e+4 : e+8]))
		}
		valueSize := num * tiffTypeSize(typ)
		if num != 0 && valueSize/num != tiffTypeSize(typ) {
			valueSize = uint64(len(data) + 1)
		}
		valueField := e + 8
		fieldSize := 4
		if info.big {
			valueField = e + 12
			fieldSize = 8
		}
		entry := tiffEntry{tag: tag, typ: typ, count: num, entryOffset: e}
		if valueSize <= uint64(fieldSize) {
			entry.value = append([]byte(nil), data[valueField:valueField+fieldSize]...)
			entry.inline = true
		} else {
			if info.big {
				if valueField+8 > len(data) {
					continue
				}
				entry.valueOffset = ord.Uint64(data[valueField : valueField+8])
			} else {
				entry.valueOffset = uint64(ord.Uint32(data[valueField : valueField+4]))
			}
			if entry.valueOffset <= uint64(len(data)) && valueSize <= uint64(len(data))-entry.valueOffset {
				entry.value = append([]byte(nil), data[entry.valueOffset:entry.valueOffset+valueSize]...)
			}
		}
		entries = append(entries, entry)
	}
	if declaredCount > (^uint64(0)-base)/uint64(info.entrySize) {
		return entries, 0, true
	}
	nextPos := base + declaredCount*uint64(info.entrySize)
	if nextPos+uint64(info.offsetBytes) > uint64(len(data)) {
		return entries, 0, true
	}
	var next uint64
	if info.big {
		next = ord.Uint64(data[nextPos : nextPos+8])
	} else {
		next = uint64(ord.Uint32(data[nextPos : nextPos+4]))
	}
	return entries, next, true
}

func inspectTIFF(data []byte) (bool, bool, []string) {
	info, ok := tiffLayout(data)
	if !ok {
		return false, false, []string{"not a TIFF"}
	}
	if info.first == 0 || info.first > uint64(len(data)) || uint64(info.countBytes) > uint64(len(data))-info.first {
		return false, false, []string{"TIFF with no image file directories"}
	}
	findings := []string{}
	var c2pa, ai bool
	queue := []uint64{info.first}
	seen := map[uint64]bool{}
	for len(queue) > 0 && len(seen) < 4096 {
		off := queue[0]
		queue = queue[1:]
		if off == 0 || seen[off] {
			continue
		}
		seen[off] = true
		entries, next, valid := readTIFFIFD(data, info, off)
		if !valid {
			continue
		}
		for _, e := range entries {
			hits := containsAny(tiffEntryPayload(e), append(aiMetaHints, c2paMarkers...))
			if len(hits) > 0 {
				ai = true
				if isC2PAHit(hits) {
					c2pa = true
				}
				findings = append(findings, fmt.Sprintf("TIFF tag %d: %s", e.tag, strings.Join(hits[:minInt(6, len(hits))], ", ")))
			}
			if name, known := tiffMetadataTags[e.tag]; known {
				label := "tag"
				if e.tag == 34665 || e.tag == 34853 || e.tag == 40965 {
					label = "sub-IFD"
				}
				findings = append(findings, fmt.Sprintf("TIFF %s %d (%s) present", label, e.tag, name))
			}
			if isTIFFPointerTag(e.tag) {
				if ptr, ok := tiffEntryPointer(info, e); ok && ptr > 0 {
					queue = append(queue, ptr)
				}
			}
		}
		if next != 0 {
			queue = append(queue, next)
		}
	}
	whole := containsAny(data, c2paMarkers)
	if len(whole) > 0 && !c2pa {
		c2pa = true
		ai = true
		if len(whole) > 6 {
			whole = whole[:6]
		}
		findings = append(findings, "byte-scan C2PA markers: "+strings.Join(whole[:minInt(6, len(whole))], ", "))
	}
	if len(findings) == 0 {
		findings = append(findings, "no TIFF metadata tags found")
	}
	return c2pa, ai || c2pa, findings
}

func stripTIFF(data []byte, stripAll bool) ([]byte, []string) {
	info, ok := tiffLayout(data)
	if !ok {
		return data, []string{"not TIFF"}
	}
	ifds := collectTIFFIFDs(data, info)
	if len(ifds) == 0 {
		return data, []string{"not a valid TIFF (no image file directories)"}
	}
	actions := []string{}
	kept := make(map[uint64][]tiffEntry, len(ifds))
	dropRanges := [][2]uint64{}
	dropIFDRanges := [][2]uint64{}
	for _, off := range tiffIFDOffsets(ifds) {
		record := ifds[off]
		keepHere := make([]tiffEntry, 0, len(record.entries))
		for _, entry := range record.entries {
			payload := tiffEntryPayload(entry)
			markerHit := len(containsAny(payload, append(aiMetaHints, c2paMarkers...))) > 0
			if isTIFFSubIFDTag(entry.tag) {
				if ptr, pointerOK := tiffEntryPointer(info, entry); pointerOK {
					if sub, exists := ifds[ptr]; exists {
						subEnd := sub.blockEnd
						if subEnd > uint64(len(data)) {
							subEnd = uint64(len(data))
						}
						if ptr < subEnd {
							markerHit = markerHit || len(containsAny(data[ptr:subEnd], append(aiMetaHints, c2paMarkers...))) > 0
						}
						markerHit = markerHit || tiffSubIFDHasMarkers(data, info, ptr)
					}
				}
			}
			_, known := tiffMetadataTags[entry.tag]
			drop := known && (stripAll || markerHit)
			if !known && markerHit && !tiffStructuralTags[entry.tag] {
				drop = true
			}
			if !drop {
				keepHere = append(keepHere, entry)
				continue
			}
			name, knownName := tiffMetadataTags[entry.tag]
			if knownName {
				name = fmt.Sprintf("%d (%s)", entry.tag, name)
			} else {
				name = fmt.Sprintf("%d (AI markers)", entry.tag)
			}
			actions = append(actions, "drop TIFF tag "+name)
			if isTIFFSubIFDTag(entry.tag) {
				if ptr, pointerOK := tiffEntryPointer(info, entry); pointerOK {
					collectTIFFDroppedIFD(data, info, ifds, ptr, &dropRanges, &dropIFDRanges, map[uint64]bool{})
				}
			} else if !entry.inline && entry.valueOffset > 0 && len(tiffEntryPayload(entry)) > 0 {
				end := entry.valueOffset + uint64(len(tiffEntryPayload(entry)))
				if end >= entry.valueOffset && end <= uint64(len(data)) {
					dropRanges = append(dropRanges, [2]uint64{entry.valueOffset, end})
				}
			}
		}
		kept[off] = keepHere
	}

	// Directories and value payloads still reachable from kept entries are
	// protected from zeroing. Metadata values can be shared by multiple tags.
	reachable := map[uint64]bool{}
	var markReachable func(uint64)
	markReachable = func(off uint64) {
		if reachable[off] {
			return
		}
		record, exists := ifds[off]
		if !exists {
			return
		}
		reachable[off] = true
		for _, entry := range kept[off] {
			if isTIFFPointerTag(entry.tag) {
				if ptr, pointerOK := tiffEntryPointer(info, entry); pointerOK {
					markReachable(ptr)
				}
			}
		}
		if record.next != 0 {
			markReachable(record.next)
		}
	}
	markReachable(info.first)
	referenced := [][2]uint64{}
	for _, off := range tiffIFDOffsets(ifds) {
		if !reachable[off] {
			continue
		}
		for _, entry := range kept[off] {
			if !entry.inline && entry.valueOffset > 0 && len(tiffEntryPayload(entry)) > 0 {
				end := entry.valueOffset + uint64(len(tiffEntryPayload(entry)))
				if end >= entry.valueOffset && end <= uint64(len(data)) {
					referenced = append(referenced, [2]uint64{entry.valueOffset, end})
				}
			}
			if isTIFFPointerTag(entry.tag) {
				if ptr, pointerOK := tiffEntryPointer(info, entry); pointerOK {
					if sub, exists := ifds[ptr]; exists {
						referenced = append(referenced, [2]uint64{ptr, sub.blockEnd})
					}
				}
			}
		}
	}
	zeroRanges := [][2]uint64{}
	for _, current := range dropRanges {
		if !tiffRangeCovered(referenced, current[0], current[1]) {
			zeroRanges = append(zeroRanges, current)
		}
	}
	for _, current := range dropIFDRanges {
		if !tiffRangeCovered(referenced, current[0], current[1]) {
			zeroRanges = append(zeroRanges, current)
		}
	}

	out := append([]byte(nil), data...)
	ord := tiffOrder(info)
	for _, off := range tiffIFDOffsets(ifds) {
		record := ifds[off]
		block := make([]byte, 0, int(record.blockEnd-off))
		if info.big {
			var count [8]byte
			ord.PutUint64(count[:], uint64(len(kept[off])))
			block = append(block, count[:]...)
		} else {
			var count [2]byte
			ord.PutUint16(count[:], uint16(len(kept[off])))
			block = append(block, count[:]...)
		}
		for _, entry := range kept[off] {
			start := entry.entryOffset
			end := start + info.entrySize
			if start >= 0 && end <= len(data) {
				block = append(block, data[start:end]...)
			}
		}
		block = appendTIFFOffset(block, info, record.next)
		regionLen := record.blockEnd - off
		if regionLen > uint64(len(out))-off {
			regionLen = uint64(len(out)) - off
		}
		if uint64(len(block)) > regionLen {
			block = block[:int(regionLen)]
		}
		copy(out[off:off+regionLen], block)
		for i := uint64(len(block)); i < regionLen; i++ {
			out[off+i] = 0
		}
	}
	for _, current := range zeroRanges {
		start, end := current[0], current[1]
		if start >= uint64(len(out)) {
			continue
		}
		if end > uint64(len(out)) {
			end = uint64(len(out))
		}
		for i := start; i < end; i++ {
			out[i] = 0
		}
	}
	if len(actions) == 0 {
		actions = append(actions, "no TIFF metadata tags removed (already clean or none matched)")
	}
	return out, actions
}

func binaryPut16(dst []byte, value uint16, order binary.ByteOrder) {
	if len(dst) >= 2 {
		order.PutUint16(dst[:2], value)
	}
}

type bmffBox struct {
	typ     []byte
	payload []byte
	total   int
	header  int
	start   int
}

func parseBMFF(data []byte, start, end int) ([]bmffBox, int) {
	if end < 0 || end > len(data) {
		end = len(data)
	}
	boxes := []bmffBox{}
	pos := start
	for pos+8 <= end {
		size := int(binary.BigEndian.Uint32(data[pos : pos+4]))
		hdr := 8
		if size == 1 {
			if pos+16 > end {
				break
			}
			u := binary.BigEndian.Uint64(data[pos+8 : pos+16])
			if u > uint64(end-pos) {
				break
			}
			size = int(u)
			hdr = 16
		} else if size == 0 {
			size = end - pos
		}
		if size < hdr || pos+size > end {
			break
		}
		boxes = append(boxes, bmffBox{append([]byte(nil), data[pos+4:pos+8]...), data[pos+hdr : pos+size], size, hdr, pos})
		pos += size
	}
	return boxes, pos
}

func buildBMFFBox(typ, payload []byte, originalHeader int) []byte {
	hdr := originalHeader
	if hdr != 16 && uint64(len(payload))+8 > uint64(^uint32(0)) {
		hdr = 16
	}
	size := hdr + len(payload)
	out := make([]byte, size)
	if hdr == 16 {
		binary.BigEndian.PutUint32(out[:4], 1)
		binary.BigEndian.PutUint64(out[8:16], uint64(size))
	} else {
		binary.BigEndian.PutUint32(out[:4], uint32(size))
	}
	copy(out[4:8], typ)
	copy(out[hdr:], payload)
	return out
}

func freeBMFFBox(size, header int) []byte {
	if size < header || size < 8 {
		return nil
	}
	payload := make([]byte, size-header)
	return buildBMFFBox([]byte("free"), payload, header)
}

func isC2PABMFFUUID(payload []byte) bool {
	return len(payload) >= 16 && (bytes.Equal(payload[:16], c2paBMFFUUID) ||
		len(payload) >= 20 && bytes.Equal(payload[4:20], c2paBMFFUUID))
}

func containsC2PABMFFUUID(data []byte) bool {
	for pos := 0; pos+4 <= len(data); {
		offset := bytes.Index(data[pos:], []byte("uuid"))
		if offset < 0 {
			return false
		}
		offset += pos
		payload := data[offset+4:]
		if isC2PABMFFUUID(payload) {
			return true
		}
		pos = offset + 4
	}
	return false
}

func inspectISOBMFF(data []byte, format string) (bool, bool, []string) {
	boxes, end := parseBMFF(data, 0, len(data))
	if len(boxes) == 0 {
		findings := []string{}
		if whole := containsAny(data, c2paMarkers); len(whole) > 0 {
			findings = append(findings, "byte-scan C2PA markers: "+strings.Join(whole[:minInt(6, len(whole))], ", "))
		} else if containsC2PABMFFUUID(data) {
			findings = append(findings, "byte-scan C2PA BMFF content-provenance user type")
		}
		findings = append(findings, "not a valid "+strings.ToUpper(format)+" (no ISOBMFF boxes found)")
		hasC2PA := len(findings) > 1
		return hasC2PA, hasC2PA, findings
	}
	findings := []string{}
	var c2pa, ai bool
	namePrefix := strings.ToUpper(format)
	for _, b := range boxes {
		name := string(b.typ)
		low := strings.ToLower(name)
		if b.typEqual("jumb") || b.typEqual("c2pa") || strings.HasPrefix(low, "c2") {
			c2pa = true
			findings = append(findings, fmt.Sprintf("%s top-level box %s (C2PA/JUMBF manifest)", namePrefix, name))
		} else if b.typEqual("uuid") {
			if bytes.HasPrefix(b.payload, xmpUUID) {
				ai = true
				xmpHits := containsAny(b.payload[16:], append(aiMetaHints, c2paMarkers...))
				if len(xmpHits) > 0 {
					findings = append(findings, fmt.Sprintf("%s XMP uuid box: %s", namePrefix, strings.Join(xmpHits[:minInt(8, len(xmpHits))], ", ")))
				} else {
					findings = append(findings, fmt.Sprintf("%s XMP uuid box", namePrefix))
				}
				if anyHit(xmpHits, "c2pa", "contentcredentials", "jumb", "contentauth") {
					c2pa = true
				}
			} else if isC2PABMFFUUID(b.payload) {
				c2pa = true
				findings = append(findings, fmt.Sprintf("%s uuid box (C2PA content-provenance manifest, user type d8fec3d6...)", namePrefix))
			} else if hits := containsAny(b.payload, append(aiMetaHints, c2paMarkers...)); len(hits) > 0 {
				ai = true
				findings = append(findings, fmt.Sprintf("%s uuid box: %s", namePrefix, strings.Join(hits[:minInt(8, len(hits))], ", ")))
				if anyHit(hits, "c2pa", "contentcredentials", "jumb") {
					c2pa = true
				}
			}
		} else if b.typEqual("meta") && len(b.payload) >= 4 {
			metaSub, _ := parseBMFF(b.payload, 4, len(b.payload))
			for _, s := range metaSub {
				sName := string(s.typ)
				sLow := strings.ToLower(sName)
				if s.typEqual("jumb") || s.typEqual("c2pa") || strings.HasPrefix(sLow, "c2") {
					c2pa = true
					findings = append(findings, fmt.Sprintf("%s meta sub-box %s (C2PA/JUMBF container)", namePrefix, sName))
					continue
				}
				if s.typEqual("uuid") {
					if bytes.HasPrefix(s.payload, xmpUUID) {
						ai = true
						hits := containsAny(s.payload[16:], append(aiMetaHints, c2paMarkers...))
						if len(hits) > 0 {
							findings = append(findings, fmt.Sprintf("%s meta XMP uuid: %s", namePrefix, strings.Join(hits[:minInt(8, len(hits))], ", ")))
						} else {
							findings = append(findings, fmt.Sprintf("%s meta XMP uuid box", namePrefix))
						}
						if anyHit(hits, "c2pa", "contentcredentials", "jumb") {
							c2pa = true
						}
					} else if isC2PABMFFUUID(s.payload) {
						c2pa = true
						findings = append(findings, fmt.Sprintf("%s meta uuid box (C2PA content-provenance manifest)", namePrefix))
					} else if hits := containsAny(s.payload, append(aiMetaHints, c2paMarkers...)); len(hits) > 0 {
						ai = true
						findings = append(findings, fmt.Sprintf("%s meta uuid: %s", namePrefix, strings.Join(hits[:minInt(8, len(hits))], ", ")))
					}
					continue
				}
				if s.typEqual("iinf") || s.typEqual("infe") || s.typEqual("iref") || s.typEqual("iloc") || s.typEqual("xml ") || s.typEqual("bxml") {
					hits := containsAny(s.payload, append(aiMetaHints, c2paMarkers...))
					if len(hits) == 0 {
						continue
					}
					ai = true
					if anyHit(hits, "c2pa", "contentcredentials", "jumb") {
						c2pa = true
					}
					findings = append(findings, fmt.Sprintf("%s meta/%s: %s", namePrefix, sName, strings.Join(hits[:minInt(8, len(hits))], ", ")))
				}
			}
		}
	}
	if !c2pa {
		if whole := containsAny(data, c2paMarkers); len(whole) > 0 {
			c2pa = true
			findings = append(findings, "byte-scan C2PA markers: "+strings.Join(whole[:minInt(6, len(whole))], ", "))
		} else if containsC2PABMFFUUID(data) {
			c2pa = true
			findings = append(findings, "byte-scan C2PA BMFF content-provenance user type")
		}
	}
	_ = end
	return c2pa, ai || c2pa, findings
}

func anyHit(hits []string, wanted ...string) bool {
	for _, hit := range hits {
		for _, value := range wanted {
			if strings.EqualFold(hit, value) {
				return true
			}
		}
	}
	return false
}

func (b bmffBox) typEqual(s string) bool { return string(b.typ) == s }

func stripISOBMFF(data []byte, format string, stripAll bool) ([]byte, []string, error) {
	boxes, end := parseBMFF(data, 0, len(data))
	if len(boxes) == 0 {
		return data, nil, fmt.Errorf("not a valid %s (no ISOBMFF boxes found)", strings.ToUpper(format))
	}
	actions := []string{}
	out := []byte{}
	var cleanMeta func([]byte) []byte
	cleanMeta = func(payload []byte) []byte {
		if len(payload) < 4 {
			return payload
		}
		prefix := payload[:4]
		subs, scanned := parseBMFF(payload, 4, len(payload))
		clean := append([]byte(nil), prefix...)
		for _, s := range subs {
			name := string(s.typ)
			drop := false
			reason := ""
			if s.typEqual("jumb") || s.typEqual("c2pa") || strings.HasPrefix(strings.ToLower(name), "c2") {
				drop = true
				reason = "C2PA/JUMBF"
			}
			if s.typEqual("uuid") {
				switch {
				case bytes.HasPrefix(s.payload, xmpUUID):
					drop, reason = true, "XMP metadata"
				case isC2PABMFFUUID(s.payload):
					drop, reason = true, "C2PA content-provenance manifest"
				case stripAll || len(containsAny(s.payload, append(aiMetaHints, c2paMarkers...))) > 0:
					drop, reason = true, "UUID metadata"
				}
			}
			if (s.typEqual("xml ") || s.typEqual("bxml")) && (stripAll || len(containsAny(s.payload, append(aiMetaHints, c2paMarkers...))) > 0) {
				drop, reason = true, "XML metadata"
			}
			if drop {
				actions = append(actions, fmt.Sprintf("drop meta sub-box %s (%s)", name, reason))
				clean = append(clean, freeBMFFBox(s.total, s.header)...)
			} else {
				clean = append(clean, buildBMFFBox(s.typ, s.payload, s.header)...)
			}
		}
		if scanned < len(payload) {
			clean = append(clean, payload[scanned:]...)
		}
		return clean
	}
	for _, b := range boxes {
		name := string(b.typ)
		drop := false
		reason := ""
		if b.typEqual("jumb") || b.typEqual("c2pa") || strings.HasPrefix(strings.ToLower(name), "c2") {
			drop = true
			reason = "C2PA/JUMBF"
		}
		if b.typEqual("uuid") {
			switch {
			case bytes.HasPrefix(b.payload, xmpUUID):
				drop, reason = true, "XMP metadata"
			case isC2PABMFFUUID(b.payload):
				drop, reason = true, "C2PA content-provenance manifest"
			case stripAll || len(containsAny(b.payload, append(aiMetaHints, c2paMarkers...))) > 0:
				drop, reason = true, "UUID metadata"
			}
		}
		if b.typEqual("meta") {
			newPayload := cleanMeta(b.payload)
			out = append(out, buildBMFFBox(b.typ, newPayload, b.header)...)
			continue
		}
		if drop {
			actions = append(actions, fmt.Sprintf("drop top-level %s box (%s)", name, reason))
			out = append(out, freeBMFFBox(b.total, b.header)...)
		} else {
			out = append(out, buildBMFFBox(b.typ, b.payload, b.header)...)
		}
	}
	if end < len(data) {
		out = append(out, data[end:]...)
		if len(data)-end >= 8 {
			actions = append(actions, fmt.Sprintf("kept %d bytes of truncated tail (file truncated)", len(data)-end))
		}
	}
	if len(actions) == 0 {
		actions = append(actions, "no "+strings.ToUpper(format)+" metadata boxes removed (already clean or none matched)")
	}
	return out, actions, nil
}
