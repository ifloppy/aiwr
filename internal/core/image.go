// inspectImageResidualWithOptions performs the post-clean image inspection.
// It retains the local c2patool verifier, but skips exiftool (its diagnostic
// dump is not part of the clean result) and skips SynthID unless the caller
// explicitly scores the changed pixels afterward.
func inspectImageResidualWithOptions(data []byte, path string, opts Options) FileReport {
	if opts.DisableExternalTools {
		return inspectImageWithSettings(data, path, opts, false, false, false)
	}
	return inspectImageWithSettings(data, path, opts, true, false, false)
}

func inspectImageWithSettings(data []byte, path string, opts Options, runTools, runSynthID, includeExiftool bool) FileReport {
	fmtName := detectImageFormat(data)
	var c2pa, ai bool
	var findings []string
	switch fmtName {
	case "png":
		c2pa, ai, findings = inspectPNG(data)
	case "jpeg":
		c2pa, ai, findings = inspectJPEG(data)
	case "webp":
		c2pa, ai, findings = inspectWebP(data)
	case "avif", "heic":
		c2pa, ai, findings = inspectISOBMFF(data, fmtName)
	case "bmp":
		c2pa, ai, findings = inspectBMP(data)
	case "gif":
		c2pa, ai, findings = inspectGIF(data)
	case "tiff":
		c2pa, ai, findings = inspectTIFF(data)
	default:
		findings = []string{"unsupported format (PNG/JPEG/WebP/AVIF/HEIC/BMP/GIF/TIFF)"}
	}
	report := FileReport{Kind: KindImage, Path: path, Format: fmtName, HasC2PA: c2pa, HasAIMetadata: ai, Findings: findings}
	if fmtName == "unknown" {
		report.Notes = []string{"format not fully inspected; only PNG/JPEG/WebP/AVIF/HEIC/BMP/GIF/TIFF are supported"}
	}
	if opts.DisableExternalTools {
		runTools = false
		runSynthID = false
	}
	if runTools {
		report.Tools = inspectOptionalToolsWithOptions(path, data, includeExiftool)
		if c2paTool, ok := report.Tools["c2patool"].(map[string]any); ok {
			if hasManifest, ok := c2paTool["has_manifest"].(bool); ok && hasManifest {
				report.HasC2PA = true
				report.Findings = append(report.Findings, "c2patool reports a C2PA-related manifest")
			}
			if available, ok := c2paTool["available"].(bool); ok && !available {
				report.Notes = append(report.Notes, "c2patool unavailable (not found); C2PA not fully inspected by this tool")
			} else if usable, ok := c2paTool["ok"].(bool); ok && !usable {
				detail, _ := c2paTool["error"].(string)
				if detail == "" {
					detail = "no usable verdict"
				}
				report.Notes = append(report.Notes, "c2patool probe inconclusive ("+detail+"); C2PA not fully inspected by this tool")
			}
		}
	}
	if runSynthID {
		report.SynthID = detectSynthIDForOptions(data, opts)
		if synthidIsWatermarked(report.SynthID) {
			suffix := ""
			if confidence, ok := report.SynthID["confidence"].(float64); ok {
				suffix = fmt.Sprintf(" (confidence=%.3f)", confidence)
			}
			report.Findings = append(report.Findings, "SynthID pixel watermark detected"+suffix)
		} else if report.SynthID != nil {
			if detail, ok := report.SynthID["error"].(string); ok && detail != "" {
				report.Findings = append(report.Findings, "SynthID scorer inconclusive: "+detail)
			}
		}
	}
	for _, f := range report.Findings {
		report.FindingsConfidence = append(report.FindingsConfidence, findingConfidence(f))
	}
	return report
}

func findingConfidence(f string) string {
	l := strings.ToLower(f)
	// Match the upstream audit buckets: a parsed provenance structure is
	// stronger than a vendor string found inside ordinary metadata, while
	// parser notes and common typography are not actionable evidence.
	if strings.HasPrefix(l, "layer-a") && strings.HasSuffix(l, "(space)") {
		return "informational"
	}
	if strings.Contains(l, "c2patool reports") ||
		strings.Contains(l, "c2pa-related manifest") ||
		strings.Contains(l, "png chunk c2") ||
		strings.Contains(l, "png chunk cabx") ||
		strings.Contains(l, "png chunk jumb") ||
		strings.Contains(l, "png chunk jumd") ||
		strings.Contains(l, "jpeg app11 segment") ||
		strings.Contains(l, "digital_source_type") ||
		strings.Contains(l, "digitalsourcetype") ||
		strings.Contains(l, "trainedalgorithmicmedia") ||
		strings.Contains(l, "compositewithtrainedalgorithmicmedia") ||
		strings.Contains(l, "softwareagent") {
		return "confirmed"
	}
	if strings.HasPrefix(l, "info:") ||
		strings.Contains(l, "cms generator") ||
		strings.Contains(l, "customxml parts") ||
		strings.Contains(l, "xmp packet present") ||
		strings.Contains(l, "unsupported") ||
		strings.Contains(l, "not fully inspected") ||
		strings.Contains(l, "format not") ||
		strings.Contains(l, "svg <metadata> present") ||
		strings.Contains(l, "not a valid") ||
		strings.Contains(l, "partial read") ||
		strings.Contains(l, "truncated chunk") ||
		strings.Contains(l, "bad segment length") ||
		strings.Contains(l, "svg decode note") ||
		strings.Contains(l, "truncated") {
		return "informational"
	}
	if strings.Contains(l, "byte-scan") {
		return "likely_false_positive"
	}
	if strings.Contains(l, "ai:") ||
		strings.Contains(l, "marker:") ||
		strings.Contains(l, "meta:") ||
		strings.Contains(l, "frontmatter") ||
		strings.Contains(l, "json-ld") ||
		strings.Contains(l, "attr:") ||
		strings.Contains(l, "png ") ||
		strings.Contains(l, "jpeg app") ||
		strings.Contains(l, "exif") ||
		strings.Contains(l, "xmp") ||
		strings.Contains(l, "interesting") ||
		strings.Contains(l, "pdf-structured") ||
		strings.Contains(l, "layer-a") {
		return "probable"
	}
	return "informational"
}

func cleanImage(data []byte, format string, opts Options) ([]byte, []string, error) {
	stripAll := stripAllMetadata(opts)
	var out []byte
	var actions []string
	var err error
	switch format {
	case "png":
		out, actions = stripPNG(data, stripAll)
	case "jpeg":
		out, actions = stripJPEG(data, stripAll)
	case "webp":
		out, actions = stripWebP(data, stripAll)
		if len(actions) > 0 && strings.HasPrefix(actions[0], "malformed WebP:") {
			err = fmt.Errorf("%s", actions[0])
		}
	case "avif", "heic":
		out, actions, err = stripISOBMFF(data, format, stripAll)
	case "bmp":
		out, actions = stripBMP(data, stripAll)
	case "gif":
		out, actions = stripGIF(data, stripAll)
	case "tiff":
		if info, valid := tiffLayout(data); !valid || len(collectTIFFIFDs(data, info)) == 0 {
			err = errors.New("not a valid TIFF (no image file directories)")
		} else {
			out, actions = stripTIFF(data, stripAll)
		}
	default:
		err = fmt.Errorf("unsupported image format: %s", format)
	}
	return out, actions, err
}

func inspectPNG(data []byte) (bool, bool, []string) {
	if !bytes.HasPrefix(data, []byte{0x89, 'P', 'N', 'G', 0x0d, 0x0a, 0x1a, 0x0a}) {
		return false, false, []string{"not a PNG"}
	}
	var c2pa, ai bool
	findings := []string{}
	for pos := 8; pos+8 <= len(data); {
		length := int(binary.BigEndian.Uint32(data[pos : pos+4]))
		if length < 0 || pos+12+length > len(data) {
			findings = append(findings, fmt.Sprintf("truncated chunk %q", data[pos+4:minInt(pos+8, len(data))]))
			break
		}
		ctype := data[pos+4 : pos+8]
		payload := data[pos+8 : pos+8+length]
		name := string(ctype)
		if bytes.Equal(ctype, []byte("caBX")) || bytes.Equal(ctype, []byte("juMB")) || bytes.Equal(ctype, []byte("jumb")) || bytes.HasPrefix(ctype, []byte("c2")) {
			c2pa, ai = true, true
			findings = append(findings, "PNG chunk "+name+" (possible C2PA container)")
		}
		if bytes.Equal(ctype, []byte("tEXt")) || bytes.Equal(ctype, []byte("zTXt")) || bytes.Equal(ctype, []byte("iTXt")) || bytes.Equal(ctype, []byte("eXIf")) {
			decoded, exceeded := pngTextPayloadCapped(payload, ctype)
			if exceeded {
				findings = append(findings, fmt.Sprintf("PNG %s: not fully inspected (decompressed text exceeds cap)", name))
			} else {
				blob := make([]byte, 0, len(payload)+1+len(decoded))
				blob = append(blob, payload...)
				blob = append(blob, '\n')
				blob = append(blob, decoded...)
				hits := containsAny(blob, append(aiMetaHints, c2paMarkers...))
				products := pngGeneratorHits(payload, ctype)
				if len(hits) > 0 || len(products) > 0 {
					ai = true
					if isC2PAHit(hits) {
						c2pa = true
					}
					parts := make([]string, 0, 2)
					if len(hits) > 0 {
						parts = append(parts, strings.Join(hits[:minInt(8, len(hits))], ", "))
					}
					if len(products) > 0 {
						parts = append(parts, "AI generator ("+strings.Join(products[:minInt(8, len(products))], ", ")+")")
					}
					findings = append(findings, "PNG "+name+": "+strings.Join(parts, "; "))
				}
			}
		}
		pos += 12 + length
		if bytes.Equal(ctype, []byte("IEND")) {
			break
		}
	}
	whole := containsAny(data, c2paMarkers)
	if len(whole) > 0 && !c2pa {
		c2pa, ai = true, true
		findings = append(findings, "byte-scan C2PA markers: "+strings.Join(whole[:minInt(6, len(whole))], ", "))
	}
	return c2pa, ai || c2pa, findings
}

func pngTextPayload(payload, ctype []byte) []byte {
	decoded, _ := pngTextPayloadCapped(payload, ctype)
	return decoded
}

func pngTextPayloadCapped(payload, ctype []byte) ([]byte, bool) {
	switch string(ctype) {
	case "tEXt":
		if i := bytes.IndexByte(payload, 0); i >= 0 {
			return payload[i+1:], false
		}
		return payload, false
	case "zTXt":
		if i := bytes.IndexByte(payload, 0); i >= 0 && i+2 <= len(payload) {
			z, err := zlib.NewReader(bytes.NewReader(payload[i+2:]))
			if err == nil {
				b, readErr := io.ReadAll(io.LimitReader(z, maxPNGTextDecompressedBytes+1))
				z.Close()
				if int64(len(b)) > maxPNGTextDecompressedBytes {
					return nil, true
				}
				if readErr == nil {
					return b, false
				}
			}
		}
	case "iTXt":
		if i := bytes.IndexByte(payload, 0); i >= 0 && i+3 < len(payload) {
			rest := payload[i+1:]
			compressed := rest[0] == 1
			rest = rest[2:]
			if j := bytes.IndexByte(rest, 0); j >= 0 {
				rest = rest[j+1:]
			}
			if j := bytes.IndexByte(rest, 0); j >= 0 {
				rest = rest[j+1:]
			}
			if compressed {
				z, err := zlib.NewReader(bytes.NewReader(rest))
				if err == nil {
					b, e := io.ReadAll(io.LimitReader(z, maxPNGTextDecompressedBytes+1))
					z.Close()
					if int64(len(b)) > maxPNGTextDecompressedBytes {
						return nil, true
					}
					if e == nil {
						return b, false
					}
				}
			}
			return rest, false
		}
	}
	return payload, false
}

func pngGeneratorHits(payload, ctype []byte) []string {
	if !(bytes.Equal(ctype, []byte("tEXt")) || bytes.Equal(ctype, []byte("zTXt")) || bytes.Equal(ctype, []byte("iTXt"))) {
		return nil
	}
	key := payload
	if i := bytes.IndexByte(key, 0); i >= 0 {
		key = key[:i]
	}
	lowerKey := strings.ToLower(string(key))
	if lowerKey != "software" && lowerKey != "creator" && lowerKey != "parameters" {
		return nil
	}
	value := strings.ToLower(string(pngTextPayload(payload, ctype)))
	var hits []string
	for _, product := range aiGeneratorProducts {
		if strings.Contains(value, strings.ToLower(product)) {
			hits = append(hits, string(key)+"="+product)
		}
	}
	return hits
}

func pngChunk(ctype, payload []byte) []byte {
	out := make([]byte, 0, len(payload)+12)
	var n [4]byte
	binary.BigEndian.PutUint32(n[:], uint32(len(payload)))
	out = append(out, n[:]...)
	out = append(out, ctype...)
	out = append(out, payload...)
	crc := crc32IEEE(append(append([]byte(nil), ctype...), payload...))
	binary.BigEndian.PutUint32(n[:], crc)
	out = append(out, n[:]...)
	return out
}

func crc32IEEE(data []byte) uint32 {
	// A small local implementation avoids making the metadata path depend on
	// image encoders; the polynomial is the PNG/IEEE CRC-32 polynomial.
	var table [256]uint32
	for i := range table {
		c := uint32(i)
		for j := 0; j < 8; j++ {
			if c&1 != 0 {
				c = 0xedb88320 ^ c>>1
			} else {
				c >>= 1
			}
		}
		table[i] = c
	}
	crc := uint32(0xffffffff)
	for _, b := range data {
		crc = table[byte(crc)^b] ^ crc>>8
	}
	return ^crc
}

func stripPNG(data []byte, stripAll bool) ([]byte, []string) {
	if !bytes.HasPrefix(data, []byte{0x89, 'P', 'N', 'G', 0x0d, 0x0a, 0x1a, 0x0a}) {
		return data, []string{"not PNG"}
	}
	out := append([]byte(nil), data[:8]...)
	actions := []string{}
	for pos := 8; pos+8 <= len(data); {
		length := int(binary.BigEndian.Uint32(data[pos : pos+4]))
		ctype := data[pos+4 : minInt(pos+8, len(data))]
		if length < 0 || pos+12+length > len(data) {
			out = append(out, data[pos:]...)
			actions = append(actions, fmt.Sprintf("kept %d bytes of truncated chunk %s tail (file truncated)", len(data)-pos, string(ctype)))
			break
		}
		payload := data[pos+8 : pos+8+length]
		chunkEnd := pos + 12 + length
		drop := false
		decompressionExceeded := false
		name := string(ctype)
		low := strings.ToLower(name)
		if bytes.Equal(ctype, []byte("eXIf")) || bytes.Equal(ctype, []byte("caBX")) || bytes.HasPrefix(ctype, []byte("c2")) || strings.Contains(low, "jumb") {
			drop = true
		} else if bytes.Equal(ctype, []byte("tEXt")) || bytes.Equal(ctype, []byte("zTXt")) || bytes.Equal(ctype, []byte("iTXt")) {
			decoded, exceeded := pngTextPayloadCapped(payload, ctype)
			if exceeded {
				drop = true
				decompressionExceeded = true
			} else {
				blob := make([]byte, 0, len(payload)+1+len(decoded))
				blob = append(blob, payload...)
				blob = append(blob, '\n')
				blob = append(blob, decoded...)
				drop = stripAll || len(containsAny(blob, append(aiMetaHints, c2paMarkers...))) > 0 || len(pngGeneratorHits(payload, ctype)) > 0
			}
		} else if len(containsAny(append(append([]byte(nil), ctype...), payload...), c2paMarkers)) > 0 && !bytes.Equal(ctype, []byte("IHDR")) && !bytes.Equal(ctype, []byte("IDAT")) && !bytes.Equal(ctype, []byte("IEND")) && !bytes.Equal(ctype, []byte("PLTE")) && !bytes.Equal(ctype, []byte("tRNS")) && !bytes.Equal(ctype, []byte("gAMA")) && !bytes.Equal(ctype, []byte("pHYs")) && !bytes.Equal(ctype, []byte("sRGB")) && !bytes.Equal(ctype, []byte("cHRM")) && !bytes.Equal(ctype, []byte("iCCP")) {
			drop = true
		}
		if drop {
			if decompressionExceeded {
				actions = append(actions, fmt.Sprintf("drop chunk %s (decompressed text exceeds cap)", name))
			} else {
				actions = append(actions, "drop chunk "+name)
			}
		} else {
			out = append(out, data[pos:chunkEnd]...)
		}
		pos = chunkEnd
		if bytes.Equal(ctype, []byte("IEND")) {
			break
		}
	}
	if len(actions) == 0 {
		actions = append(actions, "no PNG metadata chunks removed (already clean or none matched)")
	}
	return out, actions
}

func inspectJPEG(data []byte) (bool, bool, []string) {
	if len(data) < 2 || data[0] != 0xff || data[1] != 0xd8 {
		return false, false, []string{"not JPEG"}
	}
	var c2pa, ai bool
	findings := []string{}
	i := 2
	for i < len(data) {
		if data[i] != 0xff {
			i++
			continue
		}
		for i < len(data) && data[i] == 0xff {
			i++
		}
		if i >= len(data) {
			break
		}
		marker := data[i]
		i++
		if marker == 0xda {
			break
		}
		if marker == 0xd9 {
			continue
		}
		if marker == 0xd8 || marker >= 0xd0 && marker <= 0xd7 {
			continue
		}
		if i+2 > len(data) {
			break
		}
		segLen := int(binary.BigEndian.Uint16(data[i : i+2]))
		if segLen < 2 || i+segLen > len(data) {
			findings = append(findings, fmt.Sprintf("bad segment length at marker 0x%02X", marker))
			break
		}
		payload := data[i+2 : i+segLen]
		if marker == 0xeb {
			c2pa, ai = true, true
			findings = append(findings, "JPEG APP11 segment (JUMBF/C2PA common)")
		}
		if marker == 0xe1 || marker == 0xe2 || marker == 0xed || marker == 0xee || marker == 0xeb {
			hits := containsAny(payload, append(aiMetaHints, c2paMarkers...))
			if len(hits) > 0 {
				ai = true
				if isC2PAHit(hits) {
					c2pa = true
				}
				findings = append(findings, fmt.Sprintf("JPEG APP%d: %s", marker-0xe0, strings.Join(hits[:minInt(8, len(hits))], ", ")))
			}
		}
		if marker == 0xfe {
			hits := containsAny(payload, jpegCOMHints)
			if len(hits) > 0 {
				ai = true
				if isC2PAHit(hits) {
					c2pa = true
				}
				findings = append(findings, "JPEG COM: "+strings.Join(hits[:minInt(8, len(hits))], ", "))
			}
		}
		i += segLen
	}
	whole := containsAny(data, jpegC2PAMarkers)
	if len(whole) > 0 && !c2pa {
		c2pa, ai = true, true
		findings = append(findings, "byte-scan C2PA markers: "+strings.Join(whole[:minInt(6, len(whole))], ", "))
	}
	return c2pa, ai || c2pa, findings
}

func stripJPEG(data []byte, stripAll bool) ([]byte, []string) {
	if len(data) < 2 || data[0] != 0xff || data[1] != 0xd8 {
		return data, []string{"not JPEG"}
	}
	out := append([]byte(nil), data[:2]...)
	actions := []string{}
	i := 2
	for i < len(data) {
		if data[i] != 0xff {
			out = append(out, data[i:]...)
			actions = append(actions, "copied remainder after non-marker byte")
			break
		}
		for i < len(data) && data[i] == 0xff {
			i++
		}
		if i >= len(data) {
			break
		}
		marker := data[i]
		i++
		if marker == 0xd9 {
			out = append(out, 0xff, 0xd9)
			break
		}
		if marker == 0xd8 {
			continue
		}
		if marker >= 0xd0 && marker <= 0xd7 {
			out = append(out, 0xff, marker)
			continue
		}
		if marker == 0xda {
			if i+2 > len(data) {
				break
			}
			out = append(out, 0xff, marker)
			out = append(out, data[i:]...)
			actions = append(actions, "preserved entropy-coded scan (SOS→EOF)")
			break
		}
		if i+2 > len(data) {
			out = append(out, 0xff, marker)
			out = append(out, data[i:]...)
			break
		}
		segLen := int(binary.BigEndian.Uint16(data[i : i+2]))
		if segLen < 2 || i+segLen > len(data) {
			out = append(out, 0xff, marker)
			out = append(out, data[i:]...)
			actions = append(actions, "kept truncated JPEG segment tail")
			break
		}
		payload := data[i+2 : i+segLen]
		drop := false
		if marker == 0xeb {
			drop = true
			actions = append(actions, "drop APP11 (C2PA/JUMBF)")
		} else if marker >= 0xe0 && marker <= 0xef {
			if stripAll && marker != 0xe0 {
				drop = true
				actions = append(actions, fmt.Sprintf("drop APP%d", marker-0xe0))
			} else if len(containsAny(payload, append(aiMetaHints, c2paMarkers...))) > 0 {
				drop = true
				actions = append(actions, fmt.Sprintf("drop APP%d (AI/C2PA markers)", marker-0xe0))
			}
		} else if marker == 0xfe {
			if stripAll || len(containsAny(payload, jpegCOMHints)) > 0 {
				drop = true
				actions = append(actions, "drop COM comment")
			}
		}
		if !drop {
			out = append(out, 0xff, marker)
			out = append(out, data[i:i+segLen]...)
		}
		i += segLen
	}
	if len(actions) == 0 {
		actions = append(actions, "no JPEG APP segments removed")
	}
	return out, actions
}

type webpChunk struct {
	fourcc  []byte
	payload []byte
	padding []byte
}

func parseWebP(data []byte) ([]webpChunk, []string) {
	if len(data) < 12 || !bytes.Equal(data[:4], []byte("RIFF")) || !bytes.Equal(data[8:12], []byte("WEBP")) {
		return nil, []string{"not a WebP"}
	}
	chunks := []webpChunk{}
	notes := []string{}
	declaredSize := binary.LittleEndian.Uint32(data[4:8])
	if int64(declaredSize)+8 != int64(len(data)) {
		notes = append(notes, fmt.Sprintf("RIFF size mismatch: header=%d actual=%d", int64(declaredSize)+8, len(data)))
	}
	pos := 12
	for pos+8 <= len(data) {
		size := int(binary.LittleEndian.Uint32(data[pos+4 : pos+8]))
		end := pos + 8 + size
		if end > len(data) {
			notes = append(notes, fmt.Sprintf("truncated WebP chunk %s", string(data[pos:pos+4])))
			break
		}
		padEnd := end
		if size&1 != 0 {
			padEnd++
		}
		if padEnd > len(data) {
			notes = append(notes, "truncated WebP chunk padding")
			break
		}
		chunks = append(chunks, webpChunk{append([]byte(nil), data[pos:pos+4]...), data[pos+8 : end], data[end:padEnd]})
		pos = padEnd
	}
	truncated := false
	for _, note := range notes {
		if strings.Contains(strings.ToLower(note), "truncated") {
			truncated = true
			break
		}
	}
	if pos != len(data) && !truncated {
		notes = append(notes, fmt.Sprintf("trailing WebP bytes: %d", len(data)-pos))
	}
	return chunks, notes
}

func inspectWebP(data []byte) (bool, bool, []string) {
	chunks, notes := parseWebP(data)
	if len(chunks) == 0 && len(notes) == 1 && notes[0] == "not a WebP" {
		return false, false, notes
	}
	findings := append([]string(nil), notes...)
	var c2pa, ai bool
	for _, c := range chunks {
		name := string(c.fourcc)
		if strings.EqualFold(name, "C2PA") {
			c2pa, ai = true, true
			findings = append(findings, "WebP C2PA chunk")
			continue
		}
		if name == "XMP " || name == "EXIF" {
			hits := containsAny(c.payload, append(aiMetaHints, c2paMarkers...))
			if len(hits) > 0 {
				ai = true
				if isC2PAHit(hits) {
					c2pa = true
				}
				findings = append(findings, "WebP "+name+": "+strings.Join(hits[:minInt(8, len(hits))], ", "))
			}
		}
	}
	return c2pa, ai || c2pa, findings
}

func stripWebP(data []byte, stripAll bool) ([]byte, []string) {
	chunks, notes := parseWebP(data)
	if len(chunks) == 0 && len(notes) == 1 && notes[0] == "not a WebP" {
		return data, notes
	}
	if len(notes) > 0 {
		return data, append([]string{"malformed WebP: " + strings.Join(notes, "; ")}, notes...)
	}
	kept := []webpChunk{}
	removedFlags := byte(0)
	actions := []string{}
	for _, c := range chunks {
		name := string(c.fourcc)
		drop := strings.EqualFold(name, "C2PA")
		flag := byte(0)
		switch name {
		case "ICCP":
			flag = 0x20
		case "EXIF":
			flag = 0x08
		case "XMP ":
			flag = 0x04
		}
		if flag != 0 && (stripAll || len(containsAny(c.payload, append(aiMetaHints, c2paMarkers...))) > 0) {
			drop = true
			removedFlags |= flag
		}
		if drop {
			actions = append(actions, "drop WebP chunk "+name)
			continue
		}
		kept = append(kept, c)
	}
	body := []byte("WEBP")
	for _, c := range kept {
		payload := c.payload
		if string(c.fourcc) == "VP8X" && len(payload) >= 1 && removedFlags != 0 {
			payload = append([]byte(nil), payload...)
			payload[0] &^= removedFlags
		}
		var n [4]byte
		body = append(body, c.fourcc...)
		binary.LittleEndian.PutUint32(n[:], uint32(len(payload)))
		body = append(body, n[:]...)
		body = append(body, payload...)
		if len(payload)&1 != 0 {
			if len(c.padding) > 0 {
				body = append(body, c.padding...)
			} else {
				body = append(body, 0)
			}
		}
	}
	out := append([]byte("RIFF"), make([]byte, 4)...)
	binary.LittleEndian.PutUint32(out[4:8], uint32(len(body)))
	out = append(out, body...)
	if len(actions) == 0 {
		actions = append(actions, "no WebP metadata chunks removed (already clean or none matched)")
	}
	return out, actions
}

func bmpPayloadExtent(data []byte) (int, int, bool) {
	if len(data) < 30 || !bytes.HasPrefix(data, []byte("BM")) {
		return 0, 0, false
	}
	off := int(binary.LittleEndian.Uint32(data[10:14]))
	dib := int(binary.LittleEndian.Uint32(data[14:18]))
	if dib < 40 || dib > len(data)-14 || off > len(data) {
		return 0, 0, false
	}
	w := int64(int32(binary.LittleEndian.Uint32(data[18:22])))
	h := int64(int32(binary.LittleEndian.Uint32(data[22:26])))
	bpp := int64(binary.LittleEndian.Uint16(data[28:30]))
	if w <= 0 || bpp == 0 {
		return 0, 0, false
	}
	if h < 0 {
		h = -h
	}
	var size64 int64
	compression := binary.LittleEndian.Uint32(data[30:34])
	if compression == 0 {
		row := ((w*bpp + 31) / 32) * 4
		const maxInt64 = int64(^uint64(0) >> 1)
		if h != 0 && row > maxInt64/h {
			return 0, 0, false
		}
		size64 = row * h
	} else {
		size64 = int64(binary.LittleEndian.Uint32(data[34:38]))
		if size64 == 0 {
			return 0, 0, false
		}
	}
	const maxInt = int64(^uint(0) >> 1)
	if size64 < 0 || size64 > maxInt {
		return 0, 0, false
	}
	// Keep a declared payload that extends beyond EOF as a valid extent. The
	// upstream inspector treats this as a truncated/header-only BMP and avoids
	// scanning the incomplete raster for metadata.
	return off, int(size64), true
}

func inspectBMP(data []byte) (bool, bool, []string) {
	if len(data) < 14 || !bytes.HasPrefix(data, []byte("BM")) {
		return false, false, []string{"not a BMP"}
	}
	off, size, ok := bmpPayloadExtent(data)
	if !ok {
		return false, false, []string{"BMP header not fully parsed"}
	}
	if off > len(data) || size > len(data)-off {
		return false, false, []string{"BMP has no metadata (header-only raster format)"}
	}
	end := off + size
	if end >= len(data) {
		return false, false, []string{"BMP has no metadata (header-only raster format)"}
	}
	hits := containsAny(data[end:], append(aiMetaHints, c2paMarkers...))
	if len(hits) == 0 {
		return false, false, []string{fmt.Sprintf("BMP has %d unrecognized trailing byte(s)", len(data)-end)}
	}
	return isC2PAHit(hits), true, []string{"BMP trailing metadata: " + strings.Join(hits[:minInt(6, len(hits))], ", ")}
}

func stripBMP(data []byte, stripAll bool) ([]byte, []string) {
	off, size, ok := bmpPayloadExtent(data)
	if !ok {
		return data, []string{"BMP header not fully parsed; left unchanged"}
	}
	if off > len(data) || size > len(data)-off {
		return data, []string{"no BMP trailing metadata to strip"}
	}
	end := off + size
	if end >= len(data) {
		return data, []string{"no BMP trailing metadata to strip"}
	}
	trailing := data[end:]
	hits := containsAny(trailing, append(aiMetaHints, c2paMarkers...))
	if !stripAll && len(hits) == 0 {
		return data, []string{"BMP trailing bytes kept (keep-non-ai-metadata)"}
	}
	out := append([]byte(nil), data[:end]...)
	binary.LittleEndian.PutUint32(out[2:6], uint32(end))
	reason := ""
	if len(hits) > 0 {
		reason = " (" + strings.Join(hits[:minInt(4, len(hits))], ", ") + ")"
	}
	return out, []string{fmt.Sprintf("drop %d BMP trailing byte(s)%s", len(trailing), reason)}
}

func gifSubBlocks(data []byte, pos int) (int, []byte, bool) {
	var payload []byte
	for pos < len(data) {
		size := int(data[pos])
		pos++
		if size == 0 {
			return pos, payload, true
		}
		if pos+size > len(data) {
			return pos, payload, false
		}
		payload = append(payload, data[pos:pos+size]...)
		pos += size
	}
	return pos, payload, false
}

func inspectGIF(data []byte) (bool, bool, []string) {
	if len(data) < 6 || !(bytes.HasPrefix(data, []byte("GIF87a")) || bytes.HasPrefix(data, []byte("GIF89a"))) {
		return false, false, []string{"not a GIF"}
	}
	findings := []string{}
	if len(data) < 13 {
		return false, false, []string{"truncated GIF header"}
	}
	pos := 6
	packed := data[pos+4]
	pos += 7
	if packed&0x80 != 0 {
		pos += 3 * (1 << ((packed & 7) + 1))
	}
	var c2pa, ai bool
	for pos < len(data) {
		switch data[pos] {
		case 0x3b:
			pos = len(data)
		case 0x2c:
			if pos+10 > len(data) {
				findings = append(findings, "truncated GIF image block")
				pos = len(data)
				continue
			}
			packed := data[pos+9]
			pos += 10
			if packed&0x80 != 0 {
				pos += 3 * (1 << ((packed & 7) + 1))
			}
			if pos >= len(data) {
				findings = append(findings, "truncated GIF image block")
				continue
			}
			pos++
			var valid bool
			pos, _, valid = gifSubBlocks(data, pos)
			if !valid {
				findings = append(findings, "truncated GIF image block")
				continue
			}
		case 0x21:
			if pos+2 > len(data) {
				findings = append(findings, "truncated GIF extension")
				pos = len(data)
				continue
			}
			label := data[pos+1]
			pos += 2
			var payload []byte
			var valid bool
			pos, payload, valid = gifSubBlocks(data, pos)
			if !valid {
				findings = append(findings, "truncated GIF extension")
				continue
			}
			if label == 0xfe {
				findings = append(findings, "GIF comment extension present")
				hits := containsAny(payload, append(aiMetaHints, c2paMarkers...))
				if len(hits) > 0 {
					ai = true
					findings = append(findings, "GIF comment: "+strings.Join(hits[:minInt(6, len(hits))], ", "))
				}
			}
			if label == 0xff {
				ident := payload
				if len(ident) > len(gifXMPApplicationID) {
					ident = ident[:len(gifXMPApplicationID)]
				}
				if bytes.Equal(ident, gifXMPApplicationID) {
					findings = append(findings, "GIF XMP application extension present")
					hits := containsAny(payload, append(aiMetaHints, c2paMarkers...))
					if len(hits) > 0 {
						ai = true
						if isC2PAHit(hits) {
							c2pa = true
						}
						findings = append(findings, "GIF XMP: "+strings.Join(hits[:minInt(6, len(hits))], ", "))
					}
				} else if len(ident) >= 4 && (bytes.Contains(ident, []byte("c2pa")) || bytes.Contains(ident, []byte("jumb")) || bytes.Contains(ident, []byte("C2PA")) || bytes.Contains(ident, []byte("JUMB"))) {
					c2pa = true
					findings = append(findings, "GIF application extension (possible C2PA)")
				}
			}
		default:
			pos++
		}
	}
	if whole := containsAny(data, c2paMarkers); len(whole) > 0 && !c2pa {
		c2pa = true
		findings = append(findings, "byte-scan C2PA markers: "+strings.Join(whole[:minInt(6, len(whole))], ", "))
	}
	if len(findings) == 0 {
		findings = append(findings, "no GIF metadata extensions found")
	}
	return c2pa, ai || c2pa, findings
}

func stripGIF(data []byte, stripAll bool) ([]byte, []string) {
	if len(data) < 6 || !(bytes.HasPrefix(data, []byte("GIF87a")) || bytes.HasPrefix(data, []byte("GIF89a"))) {
		return data, []string{"not GIF"}
	}
	if len(data) < 13 {
		return data, []string{"truncated GIF header"}
	}
	pos := 6
	packed := data[pos+4]
	pos += 7
	out := append([]byte(nil), data[:pos]...)
	if packed&0x80 != 0 {
		gctSize := 3 * (1 << ((packed & 7) + 1))
		out = append(out, data[pos:minInt(pos+gctSize, len(data))]...)
		pos += gctSize
	}
	actions := []string{}
	for pos < len(data) {
		start := pos
		switch data[pos] {
		case 0x3b:
			out = append(out, data[pos:]...)
			pos = len(data)
		case 0x2c:
			if pos+10 > len(data) {
				out = append(out, data[pos:]...)
				pos = len(data)
				actions = append(actions, "kept truncated GIF image tail")
				continue
			}
			packed := data[pos+9]
			pos += 10
			if packed&0x80 != 0 {
				pos += 3 * (1 << ((packed & 7) + 1))
			}
			if pos >= len(data) {
				out = append(out, data[start:]...)
				pos = len(data)
				continue
			}
			pos++
			var valid bool
			pos, _, valid = gifSubBlocks(data, pos)
			if !valid {
				out = append(out, data[start:]...)
				pos = len(data)
				actions = append(actions, "kept truncated GIF image tail")
				continue
			}
			out = append(out, data[start:pos]...)
		case 0x21:
			if pos+2 > len(data) {
				out = append(out, data[pos:]...)
				pos = len(data)
				continue
			}
			label := data[pos+1]
			pos += 2
			var payload []byte
			var valid bool
			pos, payload, valid = gifSubBlocks(data, pos)
			if !valid {
				out = append(out, data[start:]...)
				pos = len(data)
				actions = append(actions, "kept truncated GIF extension tail")
				continue
			}
			drop := false
			if label == 0xfe {
				drop = stripAll || len(containsAny(payload, append(aiMetaHints, c2paMarkers...))) > 0
				if drop {
					actions = append(actions, "drop GIF comment extension")
				}
			}
			if label == 0xff {
				ident := payload
				if len(ident) > 11 {
					ident = ident[:11]
				}
				hits := containsAny(payload, append(aiMetaHints, c2paMarkers...))
				switch {
				case bytes.Equal(ident, gifXMPApplicationID):
					drop = stripAll || len(hits) > 0
					if drop {
						actions = append(actions, "drop GIF XMP application extension")
					}
				case bytes.Equal(ident, []byte("NETSCAPE2.0")) || bytes.Equal(ident, []byte("ICCRGBG1012")):
					drop = len(hits) > 0
					if drop {
						actions = append(actions, "drop GIF control application extension")
					}
				default:
					drop = stripAll || len(hits) > 0
					if drop {
						actions = append(actions, "drop GIF application extension")
					}
				}
			}
			if !drop {
				out = append(out, data[start:pos]...)
			}
		default:
			out = append(out, data[pos:]...)
			pos = len(data)
		}
	}
	if len(actions) == 0 {
		actions = append(actions, "no GIF metadata blocks removed (already clean or none matched)")
	}
	return out, actions
}

